package com.meetily.mobile.licences

/**
 * Licence terms that restrict what a model may be used for and require the
 * restrictions to reach the people who use it: Gemma Terms of Use §3.1, Health
 * AI Developer Foundations Terms of Use §3.1, and the Llama Community License
 * §1.b.iv (its Acceptable Use Policy binds whoever uses the model). Recap asks
 * for these once per family, before the first download of a model under one
 * (see ModelTerms), and its Terms of Use carry them.
 *
 * [id] names the stored acceptance, so it must never change. Raise [version]
 * when a publisher changes its terms enough that everyone should be asked
 * again.
 */
enum class TermsFamily(
    val id: String,
    val version: Int,
    /** The agreement itself. */
    val termsUrl: String,
    /** The use policy the agreement incorporates by reference. */
    val policyUrl: String
) {
    GEMMA(
        "gemma", 1,
        "https://ai.google.dev/gemma/terms",
        "https://ai.google.dev/gemma/prohibited_use_policy"
    ),
    HAI_DEF(
        "hai_def", 1,
        "https://developers.google.com/health-ai-developer-foundations/terms",
        "https://developers.google.com/health-ai-developer-foundations/prohibited-use-policy"
    ),
    LLAMA_3_2(
        "llama3_2", 1,
        "https://github.com/meta-llama/llama-models/blob/main/models/llama3_2/LICENSE",
        "https://www.llama.com/llama3_2/use-policy"
    ),
    LLAMA_3_1(
        "llama3_1", 1,
        "https://github.com/meta-llama/llama-models/blob/main/models/llama3_1/LICENSE",
        "https://llama.meta.com/llama3_1/use-policy"
    );

    /** Llama Community License §1.b.i: "Built with Llama", shown prominently. */
    val builtWithLlama: Boolean
        get() = this == LLAMA_3_2 || this == LLAMA_3_1

    /** True while [storedVersion] (0 when never accepted) predates these terms. */
    fun needsAcceptance(storedVersion: Int): Boolean = needsAcceptance(version, storedVersion)

    companion object {
        /** An acceptance stands only for the version of the terms it was given for. */
        fun needsAcceptance(currentVersion: Int, storedVersion: Int): Boolean =
            storedVersion < currentVersion
    }
}

/**
 * The licence a downloadable model is published under, as the pickers and
 * the acceptance dialog name it. Mirrors part two of notices.txt (generated by
 * android/scripts/build_notices.py); ModelLicencesTest fails when a model's
 * "Licence:" line there names a different licence from its entry here.
 */
enum class Licence(val family: TermsFamily? = null) {
    MIT,
    APACHE_2,
    CC_BY_4,
    GEMMA(TermsFamily.GEMMA),
    HAI_DEF(TermsFamily.HAI_DEF),
    LLAMA_3_2(TermsFamily.LLAMA_3_2),
    LLAMA_3_1(TermsFamily.LLAMA_3_1),

    /**
     * Not confirmed from a primary source for this release. The publisher's
     * page linked in notices.txt sets the terms. Never upgrade a model from
     * here to a named licence without reading that page.
     */
    SEE_MODEL_PAGE
}

/**
 * Licence per model key, across every catalogue (WhisperModels, NemoModels,
 * DiarizationModels, LocalLlmModels). Keys are unique across catalogues, which
 * ModelLicencesTest checks, so a key alone identifies the model.
 *
 * Every downloadable model must be listed: a model missing here would download
 * with no licence shown and no acceptance asked, so the test fails instead.
 */
object ModelLicences {

    private val WHISPER_KEYS = listOf(
        "tiny.en", "tiny", "base.en", "base",
        "small.en-q5_1", "small-q5_1", "small.en", "small",
        "large-v3-turbo-q5_0"
    )

    private val BY_KEY: Map<String, Licence> = buildMap {
        // OpenAI's README: "Whisper's code and model weights are released
        // under the MIT License."
        WHISPER_KEYS.forEach { put(it, Licence.MIT) }

        // sherpa-onnx's model cards for both conversions: CC BY 4.0.
        put("parakeet-tdt-v2", Licence.CC_BY_4)
        put("parakeet-tdt-v3", Licence.CC_BY_4)
        // Moondream's model card and the sherpa-onnx conversion's: CC BY 4.0,
        // credited to Moondream (the weights) and NVIDIA (v3, which they
        // post-train) in notices.txt.
        put("parakeet-ultra", Licence.CC_BY_4)
        put("nemotron-3.5", Licence.SEE_MODEL_PAGE)
        put("nemotron-en", Licence.SEE_MODEL_PAGE)

        // WeSpeaker's docs/pretrained.md: VoxCeleb models follow the
        // dataset's CC BY 4.0.
        put("resnet34-en", Licence.CC_BY_4)
        put("resnet293-en", Licence.CC_BY_4)
        put("resnet152-en", Licence.CC_BY_4)
        put("titanet-large-en", Licence.SEE_MODEL_PAGE)
        put("titanet-en", Licence.SEE_MODEL_PAGE)
        // 3D-Speaker's README: "released under the Apache License 2.0".
        put("campplus-zh-en", Licence.APACHE_2)

        // Qwen2.5 README: everything except the 3B and 72B is Apache 2.0.
        put("qwen2.5-1.5b", Licence.APACHE_2)
        put("qwen2.5-0.5b", Licence.APACHE_2)
        // Qwen/Qwen3.5-2B, Qwen/Qwen3.5-4B and Qwen/Qwen3.5-9B ship the
        // unmodified Apache License 2.0 as their LICENSE file.
        put("qwen35-2b", Licence.APACHE_2)
        put("qwen35-4b", Licence.APACHE_2)
        put("qwen3.5-9b", Licence.APACHE_2)
        put("llama3.2-3b", Licence.LLAMA_3_2)
        put("llama3.1-8b", Licence.LLAMA_3_1)
        put("gemma3-1b", Licence.GEMMA)
        put("gemma3-4b", Licence.GEMMA)
        // Gemma 4 is not under the Gemma Terms: Google's licence page for it
        // (ai.google.dev/gemma/docs/gemma_4_license) is the Apache License
        // 2.0, with no use policy attached, so it asks for no acceptance.
        // The same for unsloth's conversions and Google's QAT builds.
        put("gemma4-e2b", Licence.APACHE_2)
        put("gemma4-e2b-qat", Licence.APACHE_2)
        put("gemma4-e4b", Licence.APACHE_2)
        put("gemma4-e4b-qat", Licence.APACHE_2)
        put("mistral-7b", Licence.SEE_MODEL_PAGE)
        // A Gemma 3 variant, but Google-Health's README puts it under the
        // Health AI Developer Foundations terms, not the Gemma Terms.
        put("medgemma-4b", Licence.HAI_DEF)
    }

    /** Null for a key no catalogue defines. */
    fun forKey(key: String): Licence? = BY_KEY[key]

    /** The family whose terms must be accepted before [key] downloads, if any. */
    fun familyFor(key: String): TermsFamily? = BY_KEY[key]?.family

    /** Every key with a licence entry. */
    val keys: Set<String>
        get() = BY_KEY.keys
}
